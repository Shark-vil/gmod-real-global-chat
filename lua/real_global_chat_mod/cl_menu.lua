local function open_menu()
	local main_frame = vgui.Create('DFrame')
	main_frame:SetTitle('RGChat Menu')
	main_frame:SetSize(510, 450)
	main_frame:Center()
	main_frame:SetDraggable(false)
	main_frame:MakePopup()

	local main_panel = vgui.Create('DPanel', main_frame)
	main_panel:Dock(FILL)
	main_panel:SetBackgroundColor(Color(0, 0, 0))

	local scroll_panel = vgui.Create('DScrollPanel', main_panel)
	scroll_panel:Dock(FILL)

	local checkbox_modstate = scroll_panel:Add('DCheckBoxLabel')
	checkbox_modstate:SetConVar('cl_real_global_chat_status')
	checkbox_modstate:SetText('Global Chat')
	checkbox_modstate:SizeToContents()
	checkbox_modstate:SetTooltip('Enables or disables global chat')
	checkbox_modstate:Dock(TOP)
	checkbox_modstate:SetTextColor(Color(255, 255, 255))
	checkbox_modstate:DockMargin(15, 15, 15, 15)
	checkbox_modstate:SetFont('Trebuchet24')

	local checkbox_country = scroll_panel:Add('DCheckBoxLabel')
	checkbox_country:SetConVar('cl_real_global_chat_country_mode')
	checkbox_country:SetText('Chat country mode')
	checkbox_country:SizeToContents()
	checkbox_country:SetTooltip('If active, you will only talk to your country.')
	checkbox_country:Dock(TOP)
	checkbox_country:SetTextColor(Color(255, 255, 255))
	checkbox_country:DockMargin(15, 15, 15, 15)
	checkbox_country:SetFont('Trebuchet24')

	local checkbox_mapname = scroll_panel:Add('DCheckBoxLabel')
	checkbox_mapname:SetConVar('cl_real_global_chat_visible_player_map_name')
	checkbox_mapname:SetText('Chat users map display')
	checkbox_mapname:SizeToContents()
	checkbox_mapname:SetTooltip('If active, you will see what maps players are playing on.')
	checkbox_mapname:Dock(TOP)
	checkbox_mapname:SetTextColor(Color(255, 255, 255))
	checkbox_mapname:DockMargin(15, 15, 15, 15)
	checkbox_mapname:SetFont('Trebuchet24')

	local checkbox_ping = scroll_panel:Add('DCheckBoxLabel')
	checkbox_ping:SetConVar('cl_real_global_chat_ping_sound')
	checkbox_ping:SetText('Ping SFX')
	checkbox_ping:SizeToContents()
	checkbox_ping:SetTooltip('If active, you will hear a sound when you are pinged.')
	checkbox_ping:Dock(TOP)
	checkbox_ping:SetTextColor(Color(255, 255, 255))
	checkbox_ping:DockMargin(15, 15, 15, 15)
	checkbox_ping:SetFont('Trebuchet24')

	local checkbox_filter = scroll_panel:Add('DCheckBoxLabel')
	checkbox_filter:SetConVar('cl_real_global_chat_filter')
	checkbox_filter:SetText('Chat filter')
	checkbox_filter:SizeToContents()
	checkbox_filter:SetTooltip('Enables or disables the profanity and ban-word filter.')
	checkbox_filter:Dock(TOP)
	checkbox_filter:SetTextColor(Color(255, 255, 255))
	checkbox_filter:DockMargin(15, 15, 15, 15)
	checkbox_filter:SetFont('Trebuchet24')

	local checkbox_filter_strict = scroll_panel:Add('DCheckBoxLabel')
	checkbox_filter_strict:SetConVar('cl_real_global_chat_filter_strict')
	checkbox_filter_strict:SetText('Strict filter')
	checkbox_filter_strict:SizeToContents()
	checkbox_filter_strict:SetTooltip('If strict filter is active, the entire row will be hidden if ban-words are present. Doesn\'t work without active customization above!')
	checkbox_filter_strict:Dock(TOP)
	checkbox_filter_strict:SetTextColor(Color(255, 255, 255))
	checkbox_filter_strict:DockMargin(15, 15, 15, 15)
	checkbox_filter_strict:SetFont('Trebuchet24')

	local checkbox_syncplayers = scroll_panel:Add('DCheckBoxLabel')
	checkbox_syncplayers:SetConVar('sv_real_global_chat_sync_players')
	checkbox_syncplayers:SetText('[Dev Preview] Player synchronization (Nextbot)')
	checkbox_syncplayers:SizeToContents()
	checkbox_syncplayers:SetTooltip('If active, you will see other players on the map as nexbots (in development)')
	checkbox_syncplayers:Dock(TOP)
	checkbox_syncplayers:SetTextColor(Color(255, 255, 255))
	checkbox_syncplayers:DockMargin(15, 15, 15, 15)
	checkbox_syncplayers:SetFont('Trebuchet24')
end
concommand.Add('rgchat_menu', open_menu)